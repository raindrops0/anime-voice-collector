"""Generate the web app's shared answer types from the Python models."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from avoc.contracts import ChangeView, ClipView, JobView, SummaryView

NAMES = {
    "ClipView": "Clip",
    "GuessView": "Guess",
    "CountsView": "Counts",
    "RoleView": "Role",
    "SpokenView": "Spoken",
    "EpisodeView": "Episode",
    "ModelView": "Model",
    "SummaryView": "Summary",
    "ChangeView": "ChangeResult",
    "JobView": "Job",
}


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return NAMES.get(name, name)
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  {key}{'' if key in required else '?'}: {ts(value)};"
                for key, value in schema["properties"].items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def render() -> str:
    definitions = {}
    for model in (ClipView, SummaryView, ChangeView, JobView):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    lines = ["// Generated by scripts/generate_contracts.py. Do not edit by hand."]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export type {NAMES.get(name, name)} = {ts(schema)};")
    lines.extend(
        [
            'export type Status = Clip["status"];',
            "export type Roles = Record<string, Role | undefined>;",
        ]
    )
    return "\n\n".join(lines) + "\n"


if __name__ == "__main__":
    path = Path(__file__).resolve().parents[1] / "web/src/generated.ts"
    content = render()
    if "--check" in sys.argv:
        # Formatting is owned by Prettier; compare the types without whitespace.
        if not path.exists() or "".join(path.read_text(encoding="utf-8").split()) != "".join(
            content.split()
        ):
            raise SystemExit("Shared web types changed; run scripts/generate_contracts.py")
    else:
        path.write_text(content, encoding="utf-8")
